def raw_pages():
    """The page bodies as they sit on disk: the RAW index gen_quotes.py uses.

    load_pages(clean=True) is called only to get the page split; the text counted
    is the raw element, with running heads and folios in it, which is what
    gen_quotes.py's raw_hits() counts. That is why 'condenser' is 225 here and 218
    on GATE: the extra seven are in furniture the quote index strips.
    """
    return [(pp, raw) for _fp, pp, _it, raw, _o in GQ.load_pages(TXT, clean=True)]


def norm_pages(clean):
    """The normalised index, per page. clean=True is GATE, False is KEEP."""
    return [(pp, GQ.normalise(body))
            for _fp, pp, body, _raw, _o in GQ.load_pages(TXT, clean=clean)]


def count(term, pages, lo=None, hi=None):
    """(total, {printed_page: n}) over a normalised index, optionally scoped."""
    t = GQ.normalise(term)
    total, per = 0, {}
    for pp, body in pages:
        if lo is not None and not (lo <= pp <= hi):
            continue
        n = body.count(t)
        if n:
            per[pp] = per.get(pp, 0) + n
            total += n
    return total, per


def raw_count(term, pages):
    t = term.lower()
    total, per = 0, {}
    for pp, body in pages:
        n = body.lower().count(t)
        if n:
            per[pp] = per.get(pp, 0) + n
            total += n
    return total, per


def pages_str(per):
    if not per:
        return "-"
    return ", ".join(f"{p}({n})" if n > 1 else str(p) for p, n in sorted(per.items()))


def main():
    terms = sys.argv[1:] or [t for t, _ in VOLUME]
    rp = raw_pages()
    gp = norm_pages(True)
    kp = norm_pages(False)
    print(f"source: {TXT}")
    print(f"page bodies: {len(rp)}   printed pages: "
          f"{min(pp for pp, _ in rp)} to {max(pp for pp, _ in rp)}   "
          f"printed page = scan file - {GQ.PAGE_OFFSET}")
    print(f"\n| search term | RAW | GATE | KEEP | printed pages (RAW) |")
    print("|---|---|---|---|---|")
    for t in terms:
        r, _rp = raw_count(t, rp)
        g, _gp = count(t, gp)
        k, _kp = count(t, kp)
        _r2, rpg = raw_count(t, rp)
        print(f"| `{t}` | {r} | {g} | {k} | {pages_str(rpg)} |")

    print("\nscoped, over the GATE index, by printed page range:")
    print("| term | " + " | ".join(lbl for lbl, _r in SCOPED_RANGES) + " |")
    print("|---|" + "---|" * len(SCOPED_RANGES))
    for t in SCOPED:
        cells = []
        for _lbl, (lo, hi) in SCOPED_RANGES:
            n, per = count(t, gp, lo, hi)
            cells.append(f"{n} ({pages_str(per)})" if n else "0")
        print(f"| `{t}` | " + " | ".join(cells) + " |")

    print("\nthe scan's own wrong letters, whole volume (GATE index):")
    for t in SPELLINGS:
        n, per = count(t, gp)
        print(f"  {t}: {n} at {pages_str(per)}")


if __name__ == "__main__":
    main()
