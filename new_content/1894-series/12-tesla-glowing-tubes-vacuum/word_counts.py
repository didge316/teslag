#!/usr/bin/env python3
"""The counts article 12 prints, re-run on demand.

Article 12 is `tesla-glowing-tubes-vacuum.html`, SERIES-PLAN-1894.md section 9
brief 12. For this page the counts ARE the argument: brief 12 item 2 asks what a
'capacitor' is in a book that has no such word, item 3 asks about a lamp passage
that reports no efficiency figure, and item 5 says the internet gets the energy
wrong, which is a claim about what these chapters never print. A count described
in prose ("he reports no measurements") is not checkable; a count printed as a
number, with the range it was taken over, is.

So no number in article.md is typed by hand. Each one comes from this file, which
is run again at feature-006/t7 and before any push. The term list below is the
term list the draft prints, and nothing else; the full 60-term vocabulary table
and the full 30-term scoped table are in quotes.md, generated by gen_quotes.py in
this directory, which measures them for its own reasons. This script is the small
re-run a reader can check against the article.

Three indices, the same three quotes.md defines under "THE THREE WAYS TO COUNT",
because they disagree and the disagreement is the evidence:

  RAW   case-insensitive substring count over the page bodies of
        books/extracted/tesla-1894-plain.txt exactly as they sit on disk, nothing
        normalised and no furniture stripped, which is what gen_quotes.py's
        raw_hits() counts (it reads the raw element of each page). This is the
        column quotes.md prints first and the one a reader reproducing a count
        with a grep over the file gets.
  GATE  the index books/tools/check_quotes.py and books/tools/grep_quote.py build
        by default: furniture dropped, then grep_quote.normalise (long s, S-for-8,
        a hyphen at a line break folded, whitespace collapsed, lower-cased). This
        is the index the quote gate uses, so it is the index a quote was verified
        against.
  KEEP  the same normalisation with the furniture kept (load_pages(clean=False)),
        which is the only one of the three that contains display headings, index
        entries and short all-caps lines. 'Carborundum Button for Tesla Lamps' is
        0 on RAW and 1 on the other two for exactly that reason.

Scoped counts are taken over the GATE index with the page range applied, which is
how gen_quotes.py's scoped table is built, so the two scripts cannot disagree.

Printed page = scan file page - 18 (SERIES-PLAN 0). Every page list printed here
is a list of printed pages.

Usage: python3 word_counts.py             # the tables article 12 prints
       python3 word_counts.py term ...   # one or more terms, same three indices
Exit 0 always; the point is the measurement, not a verdict.
"""
