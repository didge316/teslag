#!/usr/bin/env python3
"""The attribution map, read from the live DOM rather than from the rules.

The reviewer's objection to a table generated by re-implementing tidFor() is
correct even when the table is right: a re-implementation can drift from the
shipped matcher and still print a confident bucket per page. This reads the
number the bar actually put in the click-through link - `?tid=` inside the
`.tmg-cta-btn` href, which is the only thing ClickBank ever sees, because the
link is rel=noreferrer - so the matcher being tested is the one in the file.

It also answers the question a rules table cannot: which pages never show the bar
at all. A page shorter than CONFIG.SHOW_AFTER_PX can never scroll far enough to
trigger it, and pages like /404 or /privacy showing an offer is a product
decision somebody should make on purpose rather than inherit by accident.

Run: python3 tid-live.py [base-url]  (needs :8199, the working-tree server -
the bar's JS is not in any commit on this branch except its own)
"""
import json
import os
import subprocess
import sys
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8199"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tid-live-2026-11-19.txt")

# mobile on: the bar's own trigger is a scroll on a narrow viewport, and a
# desktop-width window is the one case the module deliberately hides the bar for.
READ = """() => {
    const bar = document.querySelector('.tmg-cta-bar');
    const btn = document.querySelector('.tmg-cta-btn');
    const f = document.querySelector('footer');
    const fr = f ? f.getBoundingClientRect() : null;
    return {
        inDom: !!bar,
        visible: !!bar && bar.classList.contains('is-visible'),
        href: btn ? btn.getAttribute('href') : null,
        label: btn ? btn.textContent.trim() : null,
        disclosure: (() => { const l = document.querySelector('.tmg-cta-label');
                             return l ? l.textContent.trim() : null; })(),
        docH: document.documentElement.scrollHeight,
        scrollY: Math.round(window.scrollY),
        // the module's own second condition, measured rather than assumed:
        // show = pastThreshold && !footerVisible, so sitting the reader on the
        // footer is the one place on a long page where the bar is *supposed*
        // to be away. The first version of this probe scrolled to the bottom
        // and reported "the bar never shows on any page" - a true reading of
        // the wrong condition. The formula is the module's (`rect.top <
        // documentElement.clientHeight`), not a stricter one, so a disagreement
        // between this and the module is a real disagreement and not an
        // instrument that hid the difference behind an extra condition.
        footerInView: fr ? (fr.top < (document.documentElement.clientHeight || innerHeight)) : null,
    };
}"""


def paths():
    out = subprocess.run(["git", "-C", os.path.join(os.path.dirname(OUT), "..", ".."),
                          "ls-tree", "-r", "--name-only", "HEAD"],
                         capture_output=True, text=True, check=True).stdout.split()
    return [p for p in out if p.endswith(".html")]


def main():
    rows = []
    with sync_playwright() as pw:
        b = pw.chromium.launch()
        for p in paths():
            url = BASE + "/" + p
            ctx = b.new_context(viewport={"width": 390, "height": 844},
                                has_touch=True, is_mobile=True)
            pg = ctx.new_page()
            try:
                pg.goto(url, wait_until="networkidle", timeout=30000)
                # mid-page, deliberately: past the 700px trigger and clear of the
                # footer, which is the reader's ordinary position and the only one
                # where both of the module's conditions are satisfied at once.
                pg.evaluate("""() => { const d = document.documentElement;
                    window.scrollTo(0, Math.min(1500, Math.max(750, d.scrollHeight / 2))); }""")
                pg.wait_for_timeout(900)
                mid = pg.evaluate(READ)
                # and at a settled bottom. Driving to a stable maximum is necessary,
                # not lazy: hiding the bar removes its own 92px reservation, which
                # shortens the document while the scroll is being applied, so a single
                # scrollTo(scrollHeight) lands a couple of hundred px short on a long
                # page and reads as "the bar never hides at the footer". It does hide;
                # the instrument has to actually arrive.
                for _ in range(6):
                    pg.evaluate("() => window.scrollTo(0, document.documentElement.scrollHeight)")
                    pg.wait_for_timeout(350)
                    d = pg.evaluate(READ)
                    if abs(d["scrollY"] - (d["docH"] - 844)) <= 2:
                        break
                d["midVisible"] = mid["visible"]
                d["midY"] = mid["scrollY"]
                d["midFooterInView"] = mid["footerInView"]
            except Exception as e:
                d = {"error": str(e).splitlines()[0][:120]}
            tid = None
            if d.get("href") and "tid=" in d["href"]:
                tid = d["href"].split("tid=", 1)[1].split("&", 1)[0]
            rows.append({"path": p, "visible": d.get("visible"), "tid": tid,
                         "docH": d.get("docH"), "midVisible": d.get("midVisible"),
                         "midY": d.get("midY"), "midFooterInView": d.get("midFooterInView"),
                         "footerInView": d.get("footerInView"),
                         "error": d.get("error")})
            ctx.close()
        b.close()

    lines = ["# what the shipped bar actually attributed each shipped page, read out of the live DOM",
             "# (`?tid=` inside .tmg-cta-btn's href - rel=noreferrer means ClickBank sees nothing else),",
             "# plus whether the bar became visible at all, plus the document height that decides",
             "# whether a short page can ever reach the 700px trigger. Generated 2026-11-19.",
             "#",
             "# 'shown' is read mid-page (past the 700px trigger, clear of the footer). 'bottom' is the",
             "# same read at a settled bottom, where the module's footerVisible condition is supposed",
             "# to take the bar away - False there is the feature, not a failure. The bottom read is",
             "# only trustworthy once the scroll has settled; see the comment in the scroll code.",
             "",
             f"{'tid':<16}{'shown':<7}{'bottom':<8}{'docH':<8}path", " " + "-" * 94]
    for r in sorted(rows, key=lambda r: (str(r["tid"]), r["path"])):
        lines.append(f"{str(r['tid']):<16}{str(r['midVisible']):<7}{str(r['visible']):<8}"
                     f"{str(r['docH']):<8}{r['path']}")
        if r.get("error"):
            lines.append(f"{'':<39}ERROR {r['error']}")
    shown = [r for r in rows if r["midVisible"]]
    short = [r for r in rows if not r["midVisible"]]
    stuck = [r for r in rows if r["visible"]]
    lines += ["", f"pages seen: {len(rows)}   bar visible mid-page: {len(shown)}   "
                  f"not visible mid-page: {len(short)}",
              f"still visible at a settled bottom (must be 0 - the footer rule): {len(stuck)}",
              "tid distribution (over pages where the bar showed):"]
    dist = {}
    for r in shown:
        dist[r["tid"]] = dist.get(r["tid"], 0) + 1
    for tid, n in sorted(dist.items(), key=lambda kv: -kv[1]):
        lines.append(f"  {tid:<16}{n}")
    if short:
        lines.append("not visible mid-page - each one is explained by the module's own conditions:")
        lines.append(" either the page cannot reach 700px of scroll, or the footer was already in")
        lines.append(" view at the probe position, which is the module hiding itself correctly:")
        for r in short:
            room = (r["docH"] or 0) - 844
            if room <= 700:
                why = "cannot reach the 700px trigger, by construction"
            elif r.get("midFooterInView"):
                why = "footer already in view where the probe put the reader - working as designed"
            else:
                why = "UNEXPLAINED - neither short nor footer-obscured; look into it"
            lines.append(f"  {r['path']:<58} docH={r['docH']} scrollable-room={room}px "
                         f"footerInView={r.get('midFooterInView')} -> {why}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


main()
